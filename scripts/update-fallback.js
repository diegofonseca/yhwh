#!/usr/bin/env node
// Regenerates src/fallback.js: one verse per language (Psalm 23:1, the
// "shepherd psalm"), used when the network is unavailable or `offline: true`.
// Run manually by maintainers: `npm run update-fallback`. Never runs on install.
import { writeFile } from 'node:fs/promises';
import { LANGUAGES } from '../src/languages.js';
import { sanitize } from '../src/text.js';

// These translations follow the Septuagint/Vulgate numbering (Psalm 23 = 22).
const LXX_NUMBERING = new Set(['synodal', 'ukrogienko', 'vulgate']);

const out = {};
for (const [code, lang] of Object.entries(LANGUAGES)) {
  const chapter = LXX_NUMBERING.has(lang.translation) ? 22 : 23;
  const url = `https://api.getbible.net/v2/${lang.translation}/19/${chapter}.json`;
  const res = await fetch(url, { signal: AbortSignal.timeout(15000) });
  if (!res.ok) throw new Error(`${code}: HTTP ${res.status} for ${url}`);
  const data = await res.json();
  const verse = data.verses.find((v) => v.verse === 1);
  out[code] = { chapter, verse: 1, text: sanitize(verse.text) };
  console.log(`${code.padEnd(8)} ${chapter}:1 ${out[code].text}`);
}

const source = `// Generated by scripts/update-fallback.js — do not edit by hand.
// Source: https://getbible.net (public domain / freely distributable translations).
export const FALLBACK = Object.freeze(${JSON.stringify(out, null, 2)});
`;
await writeFile(new URL('../src/fallback.js', import.meta.url), source);
